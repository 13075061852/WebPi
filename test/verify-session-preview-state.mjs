import assert from 'node:assert/strict';
import { createSessionPreviewState } from '../src/renderer/js/session-preview-state.mjs';
let data = '';
const storage = { getItem: () => data, setItem: (_, value) => { data = value; } };
let memory = createSessionPreviewState(storage);
const a = { sessionId: 'a', sessionFile: 'draft' }, b = { sessionId: 'b' };
assert.equal(memory.activate(a).collapsed, true);
memory.remember(false);
assert.equal(memory.activate(b).collapsed, true);
memory.remember(true);
assert.equal(memory.activate(a).collapsed, false);
assert.equal(memory.activate({ ...a, sessionFile: 'persisted.jsonl' }), null, 'File rename preserves stable session identity');
assert.equal(memory.activate(b).collapsed, true);
memory = createSessionPreviewState(storage);
assert.equal(memory.activate(a).collapsed, false, 'Persist across restart');
assert.equal(memory.activate(b).collapsed, true);
assert.equal(memory.activate({ ...a, serverId: 'remote' }).collapsed, true, 'Server scope is independent');
const broken = createSessionPreviewState({ getItem() { throw Error('blocked'); }, setItem() { throw Error('blocked'); } });
assert.equal(broken.activate(a).collapsed, true);
broken.remember(false);
assert.equal(broken.activate(b).collapsed, true);
assert.equal(broken.activate(a).collapsed, false);
console.log('PASS per-conversation preview: independent states, stable identity, persistence and unavailable storage');

memory.activate(a);
memory.rememberTarget({ kind: 'file', file: 'C:/video.mp4', mode: 'render' });
memory.remember(false);
memory.activate(b);
assert.equal(memory.activate(a).target.file, 'C:/video.mp4');
const restarted = createSessionPreviewState(storage);
assert.equal(restarted.activate(a).target.file, 'C:/video.mp4');
restarted.remember(true);
restarted.activate(b);
const closed = restarted.activate(a);
assert.equal(closed.collapsed, true);
assert.equal(closed.target.file, 'C:/video.mp4', 'Closing retains content for reopening');
console.log('PASS preview content survives switching, closing and restart');

restarted.rememberTarget({ kind: 'website', url: 'http://localhost:5001/' });
assert.equal(restarted.target().previousFile.file, 'C:/video.mp4');
restarted.rememberTarget({ kind: 'website', url: 'http://localhost:5002/' });
assert.equal(restarted.target().previousFile.file, 'C:/video.mp4');
restarted.rememberTarget(null);
assert.equal(restarted.target(), null);
assert.equal(restarted.website().url, 'http://localhost:5002/', 'Exiting browser retains the last address');
restarted.activate(b);
assert.equal(restarted.website(), null, 'Other conversations do not inherit the address');
const browserRestart = createSessionPreviewState(storage);
browserRestart.activate(a);
assert.equal(browserRestart.target(), null, 'Exited browser remains exited after restart');
assert.equal(browserRestart.website().url, 'http://localhost:5002/');
browserRestart.rememberTarget({ kind: 'file', file: 'C:/other.txt' });
assert.equal(browserRestart.website().url, 'http://localhost:5002/', 'File previews do not erase browser memory');
console.log('PASS browser exit/reentry memory, file separation and independent conversation addresses');
let drafts = createSessionPreviewState(storage);
drafts.activate({ sessionId: 'empty-before', cwd: 'C:/project', messageCount: 0 });
drafts.rememberTarget({ kind: 'website', url: 'http://localhost:5001/remembered' });
drafts.rememberTarget(null);
drafts = createSessionPreviewState(storage);
assert.equal(drafts.activate({ sessionId: 'empty-after', cwd: 'C:/project', messageCount: 0 }).lastWebsite.url, 'http://localhost:5001/remembered');
assert.equal(drafts.activate({ sessionId: 'empty-after', cwd: 'C:/project', messageCount: 1 }).lastWebsite.url, 'http://localhost:5001/remembered', 'First message carries draft memory into the durable conversation');
assert.equal(drafts.activate({ sessionId: 'other-empty', cwd: 'C:/other', messageCount: 0 }).lastWebsite, undefined);
console.log('PASS empty draft URL memory survives new startup IDs and first-message persistence');
