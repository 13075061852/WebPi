import assert from 'node:assert/strict';
import { PiBridge, HaloStore } from '../src/main/pi-bridge.mjs';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
const dir = mkdtempSync(path.join(tmpdir(), 'halo-server-prompt-'));
const bridge = new PiBridge(new HaloStore(path.join(dir,'settings.json')), {}, {sessionDir:path.join(dir,'sessions')});
bridge.servers = {list:()=>[{id:'a',name:'Server A',username:'test',host:'example.invalid',port:22},{id:'b',name:'Server B',username:'test',host:'other.invalid',port:22}]};
try {
 await bridge.start(dir);
 await bridge.newSession('a');
 const sessionA=bridge.session;
 assert.equal(PiBridge.normPath(sessionA.sessionManager.getCwd()),PiBridge.normPath(bridge.serverWorkspace('a')));
 assert.ok(sessionA.getActiveToolNames().includes('preview_inspect'));
 assert.ok(sessionA.getActiveToolNames().includes('preview_control'));
 assert.ok(sessionA.getActiveToolNames().includes('icon_library'));
 const scope=await sessionA.extensionRunner.emitBeforeAgentStart('scope',undefined,'Current working directory: C:/unrelated/Link',{});
 assert.doesNotMatch(scope.systemPrompt,/C:\/unrelated\/Link/);
 assert.match(scope.systemPrompt,/远程工作目录尚未确认/);
 const hook=await sessionA.extensionRunner.emitBeforeAgentStart('find project',undefined,'base',{});
 assert.match(hook.systemPrompt,/Server A/);
 assert.match(hook.systemPrompt,/ssh_exec/);
 let sent;
 sessionA.prompt=async text=>{sent=text;};
 await bridge.prompt('找一下kingploymer这个项目');
 assert.equal(sent,'找一下kingploymer这个项目');
 await bridge.prompt('当前预览是什么', {preview:{kind:'service',serverId:'a',port:8731,title:'广俊螺杆库',url:'http://127.0.0.1:1234/login?token=secret',status:'loaded'}});
 const previewHook=await sessionA.extensionRunner.emitBeforeAgentStart('preview',undefined,'base',{});
 assert.match(previewHook.systemPrompt,/8731/);
 assert.match(previewHook.systemPrompt,/广俊螺杆库/);
 assert.doesNotMatch(previewHook.systemPrompt,/token=secret/);
 assert.equal(sent,'当前预览是什么');
 await bridge.newSession('b');
 const other=await bridge.session.extensionRunner.emitBeforeAgentStart('find project',undefined,'base',{});
 assert.match(other.systemPrompt,/Server B/);
 assert.doesNotMatch(other.systemPrompt,/Server A/);
 assert.doesNotMatch(other.systemPrompt,/8731/);
 const original=await sessionA.extensionRunner.emitBeforeAgentStart('find project',undefined,'base',{});
 assert.match(original.systemPrompt,/Server A/);
 assert.doesNotMatch(original.systemPrompt,/Server B/);
 await bridge.newSession('a');
 await bridge.prompt('已关闭预览', {preview:null});
 const cleared=await sessionA.extensionRunner.emitBeforeAgentStart('preview',undefined,'base',{});
 assert.doesNotMatch(cleared.systemPrompt,/8731/);
 console.log('PASS original user text and per-session server system prompts');
} finally {await bridge.runtime?.dispose();}
process.exit(0);
