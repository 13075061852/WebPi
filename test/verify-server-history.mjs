import assert from 'node:assert/strict';
import { PiBridge, HaloStore } from '../src/main/pi-bridge.mjs';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
const dir=mkdtempSync(path.join(tmpdir(),'halo-server-history-'));
const store=new HaloStore(path.join(dir,'settings.json'));
const bridge=new PiBridge(store);
const file=path.join(dir,'history.jsonl');
writeFileSync(file,'');
bridge.cwd=dir;
bridge.session={sessionId:'session-a',sessionFile:file};
bridge.serverTargets.set('session-a','server-a');
store.set('serverTargets',Object.fromEntries(bridge.serverTargets));
bridge._noteSession();
const reopened=new PiBridge(new HaloStore(store.file));
assert.equal(reopened.serverTargets.get('session-a'),'server-a');
assert.equal(reopened.store.data.serverLastSessions['server-a'],file);
bridge.session={sessionId:'other',sessionFile:'other'};
bridge._noteSession({sessionId:'session-a',sessionFile:file});
assert.equal(store.data.serverLastSessions['server-a'],file);
console.log('PASS server binding and last session persist, background session records retained');
