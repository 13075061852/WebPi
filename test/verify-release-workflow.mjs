import assert from 'node:assert/strict';
import fs from 'node:fs';
import {parse} from 'yaml';
import {dependencyKey} from '../scripts/dependency-cache-key.mjs';
const lock={version:'1.0.6',packages:{'':{version:'1.0.6',dependencies:{a:'1'}},'node_modules/a':{version:'1'}}};
const bumped=structuredClone(lock);bumped.version='1.0.7';bumped.packages[''].version='1.0.7';
assert.equal(dependencyKey(lock,{},'win-x64-node24'),dependencyKey(bumped,{},'win-x64-node24'));
bumped.packages['node_modules/a'].version='2';
assert.notEqual(dependencyKey(lock,{}),dependencyKey(bumped,{}));
assert.notEqual(dependencyKey(lock,{},'node22'),dependencyKey(lock,{},'node24'));
assert.notEqual(dependencyKey(lock,{}),dependencyKey(lock,{scripts:{postinstall:'changed'}}));
const release=parse(fs.readFileSync('.github/workflows/release.yml','utf8'));
assert.equal(release.jobs.upload.needs,'build');
assert.ok(!JSON.stringify(release.jobs.upload).includes('npm ci'));
assert.ok(!JSON.stringify(release.jobs.upload).includes('npm run dist'));
const retained=release.jobs.build.steps.find(s=>s.with?.name==='windows-verified-installer');
assert.equal(retained.with['compression-level'],0);
assert.ok(retained.with.path.includes('test/results/release-artifacts.json'));
assert.ok(release.jobs.upload.steps.some(s=>s.with?.name==='windows-verified-installer'&&s.uses==='actions/download-artifact@v4'));
const action=parse(fs.readFileSync('.github/actions/windows-dependencies/action.yml','utf8'));
assert.ok(action.runs.steps.some(s=>s.run?.startsWith('npm ci')&&s.if.includes("cache-hit != 'true'")));
const warm=parse(fs.readFileSync('.github/workflows/windows-dependencies.yml','utf8'));
assert.ok(warm.on.push.branches.includes('main'),'Warm cache on default branch so future tags can restore it');
console.log('PASS release retry isolation, immutable artifact handoff, version-independent dependency cache and invalidation');
