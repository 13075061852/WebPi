import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { runOffice, summarizeOfficeResult } from '../src/main/office/tools.mjs';
import { previewDocument } from '../src/main/document-preview.mjs';
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'halo-efficiency-'));
const result=await runOffice({action:'run',script:path.resolve('assets/office-examples/pdf.cjs')},dir);
const file=result.checks[0].file;
const [a,b]=await Promise.all([previewDocument(file),previewDocument(file)]);
assert.equal(a,b,'same in-flight request is shared');
assert.equal(await previewDocument(file),a,'unchanged file uses cache');
const now=new Date(Date.now()+2000);fs.utimesSync(file,now,now);
assert.notEqual(await previewDocument(file),a,'changed file invalidates cache');
await assert.rejects(previewDocument(file,999));
const full={checks:[{text:'报告'.repeat(6000),visualChecked:false,formulaWarnings:['A1 has no cached result']}],log:'',files:[file]};
const compact=summarizeOfficeResult(full);
assert.equal(compact.checks[0].visualChecked,false);
assert.deepEqual(compact.checks[0].formulaWarnings,full.checks[0].formulaWarnings);
assert.deepEqual(compact.files,[file]);
assert.ok(JSON.stringify(compact).length<JSON.stringify(full).length/10);
console.log('PASS request sharing, cache invalidation, page bounds, compact output preserves checks');
