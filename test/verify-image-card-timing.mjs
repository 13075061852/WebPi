import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {artifactPath, replyArtifacts} from '../src/renderer/js/artifacts.mjs';
const delivered = 'C:/Users/test/My Pictures/output/元素周期表-插画版.png';
assert.deepEqual(replyArtifacts('已生成：**' + delivered.replaceAll('/', '\\') + '**（1536×1024）', 'C:/project'), [delivered]);
assert.deepEqual(replyArtifacts('已生成：\n' + delivered + '\n', 'C:/project'), [delivered]);
assert.deepEqual(replyArtifacts('[' + '图片](' + delivered + ')\n**' + delivered + '**', 'C:/project'), [delivered]);
assert.deepEqual(replyArtifacts('https://example.com/output/picture.png', 'C:/project'), []);
assert.deepEqual(replyArtifacts('**/home/test/output/海报.png**', '/home/test'), ['/home/test/output/海报.png']);
const source=fs.readFileSync('src/renderer/js/app.js','utf8');
const code=source.slice(source.indexOf('function updateImageArtifactCard('),source.indexOf('async function showTurnArtifacts('));
const context=vm.createContext({artifactPath,normPath:p=>p.toLowerCase(),formatDuration:s=>s+'秒',document:{createElement:()=>({})}});
vm.runInContext(code,context);
let label;
const button={classList:{contains:()=>true},querySelector:selector=>selector==='.artifact-meta'?{append:node=>{label=node;}}:label};
const turn={__imageResults:new Map([['original',{file:'C:/project/output/original.png',sha256:'fixture',timing:{totalMs:58000}}]])};
context.updateImageArtifactCard(button,'C:/project/output/renamed.png',turn,'C:/project','fixture');
assert.equal(label.textContent,'· 生成用时 58秒');
const first=label;
context.updateImageArtifactCard(button,'C:/project/output/renamed.png',turn,'C:/project','fixture');
assert.equal(label,first,'Refreshing must update the existing label');
label=undefined;
context.updateImageArtifactCard(button,'C:/project/output/original.png',turn,'C:/project','different');
assert.equal(label,undefined,'Replaced file must not inherit old timing');
turn.__imageResults=new Map([['old',{file:'old.png',__toolDurationMs:4000}]]);
context.updateImageArtifactCard(button,'C:/project/old.png',turn,'C:/project');
assert.equal(label.textContent,'· 生成用时 约 4秒');
console.log('PASS image card timing, rename identity, repeated render, overwritten files and historical estimate');
