import assert from 'node:assert/strict';
import { GitHubAuth } from '../src/main/github-auth.mjs';

const calls = [];
let accounts = 'octocat\nsecond-user', failure = false;
const auth = new GitHubAuth({ run: async (args) => {
  calls.push(args);
  if (args.includes('login') && failure) throw Error('Cancelled');
  if (args.includes('list')) return accounts;
  if (args.includes('logout')) accounts = 'second-user';
  return '';
} });
assert.deepEqual((await auth.status()).accounts, ['octocat', 'second-user']);
assert.equal((await auth.login()).busy, false);
assert.ok(calls.some(args => args.includes('--browser')));
assert.deepEqual(calls.find(args => args[0] === 'config'), ['config', '--global', '--replace-all', 'credential.https://github.com.helper', 'manager']);
assert.deepEqual((await auth.logout('octocat')).accounts, ['second-user']);
await assert.rejects(auth.logout('--arbitrary-option'), /未找到/);
calls.length = 0; failure = true;
await assert.rejects(auth.login(), /Cancelled/);
assert.equal(auth.busy, false);
assert.equal(calls.some(args => args[0] === 'config'), false, 'Failed login must not alter Git config');
const missing = new GitHubAuth({run: async () => { throw Error('Git unavailable'); }});
assert.equal((await missing.status()).available, false);
assert.equal(calls.some(args => args.includes('push') || args.includes('pull')), false);
const credentialCalls = [], token = 'fixture-only-token-do-not-log';
const store = { data: {}, set(key, value) { this.data[key] = value; } };
const selected = new GitHubAuth({ store, run: async (args, options) => {
  credentialCalls.push({ args, options });
  if (args.includes('list')) return 'octocat\nsecond-user';
  if (args.includes('get')) return `protocol=https\nhost=github.com\nusername=second-user\npassword=${token}\n`;
  return '';
} });
assert.equal((await selected.status()).selectedAccount, 'octocat');
assert.equal((await selected.select('second-user')).selectedAccount, 'second-user');
assert.equal((await selected.status()).selectedAccount, 'second-user');
assert.equal(await selected.credential('second-user'), token);
assert.equal(await selected.credential('second-user'), token);
assert.equal(credentialCalls.filter(call => call.args.includes('get')).length, 1, 'Credential cached in main memory');
const credentialCall = credentialCalls.find(call => call.args.includes('get'));
assert.equal(credentialCall.options.input, 'protocol=https\nhost=github.com\nusername=second-user\n\n');
assert.equal(credentialCall.options.sensitive, true);
assert.equal(JSON.stringify(store).includes(token), false, 'Never persist token in settings');
assert.equal(JSON.stringify(await selected.status()).includes(token), false, 'Never return token in account status');
assert.equal(credentialCalls.some(call => call.args.join(' ').includes(token)), false, 'Never pass token on command line');
selected.invalidate('second-user');
await selected.credential('second-user');
assert.equal(credentialCalls.filter(call => call.args.includes('get')).length, 2);
await assert.rejects(selected.select('unknown'), /先登录/);
const mismatched = new GitHubAuth({ run: async args => args.includes('list') ? 'octocat' : `username=other\npassword=${token}\n` });
await assert.rejects(mismatched.credential('octocat'), /授权异常/);
let releaseSelection, selectionCalls = 0;
const racingStore = { data: {}, set(key, value) { this.data[key] = value; } };
const racingSelection = new GitHubAuth({ store: racingStore, run: async () => {
  if (++selectionCalls === 1) return new Promise(resolve => { releaseSelection = resolve; });
  return 'octocat\nsecond-user';
} });
const oldSelection = racingSelection.select('octocat');
await racingSelection.select('second-user');
releaseSelection('octocat\nsecond-user'); await oldSelection;
assert.equal(racingStore.data.githubAccount, 'second-user', 'Older account selection cannot overwrite the latest one');
let releaseCredential;
const racingCredential = new GitHubAuth({ run: async args => args.includes('list') ? 'octocat' : new Promise(resolve => { releaseCredential = resolve; }) });
const pendingCredential = racingCredential.credential('octocat');
await new Promise(resolve => setImmediate(resolve));
racingCredential.invalidate('octocat'); releaseCredential(`username=octocat\npassword=${token}\n`);
await assert.rejects(pendingCredential, /授权已更新/);
assert.equal(racingCredential.tokens.size, 0, 'Invalidated credential response cannot repopulate the cache');
console.log('PASS GitHub browser login, account selection, isolated credential stdin/cache, no token exposure, logout and failures');
