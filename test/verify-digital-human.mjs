import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { DigitalHuman } from '../src/main/digital-human.mjs';

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'halo-digital-human-'));
const originalFetch = globalThis.fetch;
let requests = 0;
globalThis.fetch = async () => { requests++; throw Error('Local drafts must never call a cloud API'); };
try {
  const directory = path.join(root, 'drafts');
  let dimensions = { width: 720, height: 1280 };
  const service = new DigitalHuman(directory, { readImage: buffer => { assert.equal(buffer[0], 137); return dimensions; } });
  assert.deepEqual(service.state(), { photos: [], voices: [], profile: { photoId: null, photoIds: [], voiceId: null }, draft: { script: '', scene: '', action: '', resolution: '768P', ratio: '16:9' }, connected: false });
  assert.equal(fs.existsSync(directory), false, 'Empty state does not create assets or touch account data');
  const photoPath = path.join(root, 'portrait.png');
  const png = Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), Buffer.alloc(32)]);
  fs.writeFileSync(photoPath, png);
  const photo = await service.importAsset('photo', photoPath);
  assert.equal(photo.width, 720); assert.equal(photo.height, 1280);
  assert.equal(photo.quality, 'ready'); assert.equal(photo.available, true);
  assert.match(photo.previewURL, /^halo-preview:\/\/digital-human\/[0-9a-f-]{36}$/);
  assert.equal(photo.name, 'portrait.png');
  assert.equal(photo.data, undefined, 'Photos use an opaque preview rather than returning bytes');
  assert.ok(!JSON.stringify(photo).includes(root), 'Public metadata does not reveal filesystem paths');
  assert.deepEqual(fs.readFileSync(photoPath), png, 'Import never changes the original photo');
  assert.deepEqual(Buffer.from(await (await service.response(new Request(photo.previewURL))).arrayBuffer()), png);
  const photoHead = await service.response(new Request(photo.previewURL, { method: 'HEAD' }));
  assert.equal(photoHead.headers.get('content-length'), String(png.length));
  assert.equal(photoHead.headers.get('content-type'), 'image/png');
  assert.equal(await photoHead.text(), '');
  dimensions = { width: 100, height: 256 };
  await assert.rejects(service.importAsset('photo', photoPath), /边长/);
  dimensions = { width: 5761, height: 2560 };
  await assert.rejects(service.importAsset('photo', photoPath), /边长/);
  dimensions = { width: 256, height: 5760 };
  await assert.rejects(service.importAsset('photo', photoPath), /宽高比/);
  dimensions = null;
  await assert.rejects(service.importAsset('photo', photoPath), /边长/);
  assert.equal(service.state().photos.length, 1, 'Rejected images leave no ledger entries');
  dimensions = { width: 720, height: 1280 };
  await assert.rejects(new DigitalHuman(path.join(root, 'no-adapter')).importAsset('photo', photoPath), /验证尚未就绪/);

  const voicePath = path.join(root, 'my-voice.wav');
  const wav = Buffer.alloc(44 + 32000 * 2 * 10);
  wav.write('RIFF'); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVE', 8);
  wav.write('fmt ', 12); wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22);
  wav.writeUInt32LE(32000, 24); wav.writeUInt32LE(64000, 28); wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34);
  wav.write('data', 36); wav.writeUInt32LE(wav.length - 44, 40);
  fs.writeFileSync(voicePath, wav);
  const recorded = await service.importRecording(new Uint8Array(wav));
  assert.equal(recorded.mime, 'audio/wav');
  service.assetDelete(recorded.id);
  await assert.rejects(service.importRecording(new Uint8Array(45)), /录音/);
  const secondPhoto = await service.importAsset('photo', photoPath);
  assert.deepEqual(service.profileSave({ photoIds: [photo.id, secondPhoto.id] }).profile.photoIds, [photo.id, secondPhoto.id]);
  assert.throws(() => service.profileSave({ photoIds: [photo.id, photo.id] }), /9/);
  assert.deepEqual(service.assetDelete(secondPhoto.id).profile.photoIds, [photo.id]);
  service.profileSave({ photoIds: [] });

  const voice = await service.importAsset('voice', voicePath);
  assert.equal(voice.quality, 'unchecked'); assert.equal(voice.duration, null);
  assert.equal(voice.available, false); assert.equal(voice.exists, true);
  assert.deepEqual(Buffer.from(voice.data, 'base64'), wav, 'Only import returns voice bytes for local decoding');
  assert.equal(service.state().voices[0].data, undefined);
  const range = await service.response(new Request(voice.previewURL, { headers: { Range: 'bytes=0-3' } }));
  assert.equal(range.status, 206); assert.equal(await range.text(), 'RIFF');
  assert.equal(range.headers.get('content-type'), 'audio/wav');
  assert.equal((await service.response(new Request(voice.previewURL, { headers: { Range: 'bytes=999999999-' } }))).status, 416);
  assert.equal((await service.response(new Request(voice.previewURL, { method: 'POST' }))).status, 405);
  for (const duration of [0, 9.99, 300.01, Infinity, '10', null]) assert.throws(() => service.assetUpdate({ id: voice.id, duration, quality: 'ready' }), /时长/);
  assert.throws(() => service.assetUpdate({ id: voice.id, duration: 10 }), /检查结果/);
  const decoded = service.assetUpdate({ id: voice.id, duration: 10, quality: 'ready', name: '我的声音' });
  assert.equal(decoded.voices[0].available, true); assert.equal(decoded.voices[0].duration, 10);
  assert.equal(decoded.voices[0].name, '我的声音'); assert.equal(decoded.connected, false);
  assert.equal(service.assetUpdate({ id: voice.id, duration: 300, quality: 'ready' }).voices[0].duration, 300);
  assert.equal(service.assetUpdate({ id: voice.id, quality: 'unavailable' }).voices[0].duration, null);
  service.assetUpdate({ id: voice.id, duration: 10, quality: 'ready' });
  assert.throws(() => service.assetUpdate({ id: photo.id, duration: 10, quality: 'ready' }), /检查结果/);
  assert.throws(() => service.assetUpdate({ id: voice.id, name: '' }), /名称/);
  assert.throws(() => service.assetUpdate({ id: 'not-recorded', name: 'test' }), /不存在/);

  const script = '  大家好，我是小林。\n今天介绍我们的新产品。  ';
  const initialDraft = service.state().draft;
  const configured = service.profileSave({ photoId: photo.id, voiceId: voice.id, script: 'must be ignored', scene: 'must be ignored', action: 'must be ignored', ratio: '1:1' });
  assert.deepEqual(configured.profile, { photoId: photo.id, photoIds: [photo.id], voiceId: voice.id });
  assert.deepEqual(configured.draft, initialDraft, 'Saving reusable identity cannot change generation text/options');
  const saved = service.draftSave({ photoId: photo.id, voiceId: voice.id, script, scene: '明亮的办公室', action: '面向镜头微笑并挥手', ratio: '9:16', connected: true });
  assert.equal(saved.draft.script, script, 'Keep the exact draft dialogue');
  assert.equal(saved.connected, false, 'A draft cannot enable cloud connectivity');
  assert.equal(saved.draft.connected, undefined);
  assert.equal(saved.draft.photoId, undefined); assert.equal(saved.draft.voiceId, undefined);
  assert.deepEqual(saved.profile, configured.profile);
  assert.deepEqual(service.draftSave({ photoId: null, voiceId: 'unrecognized', profile: { photoId: null, photoIds: [], voiceId: null } }).profile, configured.profile, 'Old or malformed identity fields in a draft cannot change the profile');
  assert.throws(() => service.profileSave({ voiceId: photo.id }), /素材不存在/);
  assert.throws(() => service.profileSave({ photoId: '00000000-0000-4000-8000-000000000000' }), /素材不存在/);
  assert.throws(() => service.profileSave(null), /配置/);
  assert.throws(() => service.draftSave({ script: 'a'.repeat(5001) }), /台词/);
  assert.throws(() => service.draftSave({ scene: 'a'.repeat(1501) }), /场景/);
  assert.throws(() => service.draftSave({ action: 'a'.repeat(1501) }), /动作/);
  assert.equal(service.draftSave({ resolution: '2K' }).draft.resolution, '2K');
  assert.throws(() => service.draftSave({ resolution: '1080P' }), /分辨率/);
  assert.throws(() => service.draftSave({ ratio: 'adaptive' }), /比例/);
  const reloaded = new DigitalHuman(directory, { readImage: () => dimensions });
  assert.deepEqual(reloaded.state(), service.state(), 'Assets and draft survive service restart');
  assert.ok(!JSON.stringify(reloaded.state()).includes(root));
  assert.equal(requests, 0, 'Local asset selection, decoding metadata and draft saving remain offline');

  for (const badURL of [voice.previewURL.replace('digital-human', 'other'), `${voice.previewURL}?file=${encodeURIComponent(voicePath)}`, `${voice.previewURL}/../my-voice.wav`, 'halo-preview://digital-human/00000000-0000-4000-8000-000000000000']) {
    assert.equal((await service.response(new Request(badURL))).status, 404);
  }
  const corruptPath = path.join(root, 'fake.mp3'); fs.writeFileSync(corruptPath, 'not audio');
  await assert.rejects(service.importAsset('voice', corruptPath), /MP3/);
  await assert.rejects(service.importAsset('voice', photoPath), /MP3/);
  await assert.rejects(service.importAsset('photo', voicePath), /JPG/);
  await assert.rejects(service.importAsset('arbitrary', voicePath), /路径/);
  await assert.rejects(service.importAsset('voice', 'relative.wav'), /路径/);
  await assert.rejects(service.importAsset('voice', root), /文件/);
  const tooLarge = path.join(root, 'huge.wav');
  const largeHandle = fs.openSync(tooLarge, 'w'); fs.ftruncateSync(largeHandle, 20 * 1024 * 1024 + 1); fs.closeSync(largeHandle);
  await assert.rejects(service.importAsset('voice', tooLarge), /20 MB/);
  const mp3Path = path.join(root, 'sample.mp3'); fs.writeFileSync(mp3Path, Buffer.concat([Buffer.from('ID3'), Buffer.alloc(100)]));
  assert.equal((await service.importAsset('voice', mp3Path)).mime, 'audio/mpeg');
  const m4aPath = path.join(root, 'sample.m4a'); fs.writeFileSync(m4aPath, Buffer.concat([Buffer.from([0, 0, 0, 24]), Buffer.from('ftypM4A '), Buffer.alloc(100)]));
  assert.equal((await service.importAsset('voice', m4aPath)).mime, 'audio/mp4');

  const beforeLegacy = service.read();
  const legacy = { version: 1, assets: beforeLegacy.assets, draft: { ...beforeLegacy.draft, photoId: photo.id, voiceId: voice.id } };
  const legacyText = JSON.stringify(legacy, null, 2);
  fs.writeFileSync(service.file, legacyText);
  const migrated = service.state();
  assert.deepEqual(migrated.profile, { photoId: photo.id, photoIds: [photo.id], voiceId: voice.id });
  assert.deepEqual(migrated.draft, beforeLegacy.draft, 'Migration preserves exact script, scene, action and generation options');
  assert.equal(migrated.photos.length + migrated.voices.length, legacy.assets.length);
  assert.equal(fs.readFileSync(service.file, 'utf8'), legacyText, 'Read-only migration does not write the ledger');
  assert.deepEqual(service.profileSave({ photoId: null, script: 'ignored during migration' }).draft, beforeLegacy.draft);
  const separated = JSON.parse(fs.readFileSync(service.file, 'utf8'));
  assert.deepEqual(separated.assets, legacy.assets, 'Migration preserves all assets and metadata');
  assert.deepEqual(separated.profile, { photoId: null, photoIds: [], voiceId: voice.id });
  assert.deepEqual(separated.draft, beforeLegacy.draft);
  assert.equal(Object.hasOwn(separated.draft, 'photoId'), false);
  assert.equal(Object.hasOwn(separated.draft, 'voiceId'), false);
  separated.draft.photoId = photo.id; separated.draft.voiceId = null;
  fs.writeFileSync(service.file, JSON.stringify(separated));
  assert.deepEqual(service.state().profile, separated.profile, 'An existing profile wins over stale legacy draft selectors');
  service.draftSave({ script: beforeLegacy.draft.script });
  assert.equal(Object.hasOwn(JSON.parse(fs.readFileSync(service.file, 'utf8')).draft, 'photoId'), false);
  service.profileSave({ photoId: photo.id });

  const linked = new DigitalHuman(path.join(root, 'linked-draft'));
  const external = path.join(root, 'outside-draft');
  fs.mkdirSync(linked.directory); fs.mkdirSync(external);
  fs.symlinkSync(external, linked.assetsDirectory, 'junction');
  await assert.rejects(linked.importAsset('voice', voicePath), /目录/);
  assert.deepEqual(fs.readdirSync(external), [], 'Reject an asset directory link that leads outside the draft directory');

  const photoCopy = service.assetFile(service.read().assets.find(asset => asset.id === photo.id));
  fs.unlinkSync(photoCopy);
  assert.equal(service.state().photos[0].status, 'deleted');
  assert.equal((await service.response(new Request(photo.previewURL))).status, 404);
  const draftBeforeDelete = service.state().draft;
  const afterPhotoDelete = service.assetDelete(photo.id);
  assert.equal(afterPhotoDelete.profile.photoId, null);
  assert.equal(afterPhotoDelete.profile.voiceId, voice.id, 'Deleting a photo preserves the configured voice');
  assert.deepEqual(afterPhotoDelete.draft, draftBeforeDelete, 'Deleting identity assets preserves all generation text/options');
  assert.deepEqual(fs.readFileSync(photoPath), png, 'Deleting an asset never deletes the original photo');
  const afterDelete = service.assetDelete(voice.id);
  assert.equal(afterDelete.profile.voiceId, null);
  assert.deepEqual(afterDelete.draft, draftBeforeDelete);
  assert.ok(!afterDelete.voices.some(asset => asset.id === voice.id));
  assert.equal((await service.response(new Request(voice.previewURL))).status, 404);
  assert.deepEqual(fs.readFileSync(voicePath), wav, 'Deleting an asset never deletes the original voice sample');
  assert.throws(() => service.assetDelete('../my-voice.wav'), /无效/);
  assert.equal(requests, 0);
  console.log('PASS local photo/audio validation, separate profile/draft persistence, lossless legacy migration, decoded duration gates, opaque byte ranges, removed assets and zero cloud requests');
} finally {
  globalThis.fetch = originalFetch;
  assert.equal(path.dirname(path.resolve(root)), path.resolve(os.tmpdir()));
  assert.ok(path.basename(root).startsWith('halo-digital-human-'));
  fs.rmSync(root, { recursive: true, force: true });
}
